/**
 * lockfile 파서 변형 fixture. 기대값은 `name@version` 키(정렬·중복 제거)로 비교한다.
 * Backend Plan "파서 정규화 규칙"의 변형을 하나씩 담는다.
 */

const BOM = String.fromCharCode(0xfeff);

/** UTF-8 BOM + CRLF 변형 */
export function withBomAndCrlf(content: string): string {
  return `${BOM}${content.replace(/\n/g, "\r\n")}`;
}

