/**
 * 스캔 시나리오용 repo 파일 생성기. 파서 변형 fixture 는 `lockfiles/__fixtures__` 에 있다.
 * 생성기는 각 도구가 실제로 만드는 형식을 따른다(파서가 읽는 부분 + 형식 표지).
 */

export interface PkgJsonInput {
  name?: string;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  workspaces?: unknown;
}

export function pkgJson(input: PkgJsonInput = {}): string {
  const { name = "app", ...rest } = input;
  return `${JSON.stringify({ name, version: "1.0.0", private: true, ...rest }, null, 2)}\n`;
}

/** 패키지 이름 → 정확한 버전 (lockfile 에 1번씩 들어간다) */
export type PackageVersions = Record<string, string>;

function tarballName(name: string): string {
  return name.split("/").pop() ?? name;
}

export function npmLockV3(packages: PackageVersions, rootDeps: Record<string, string> = {}): string {
  const entries: Record<string, unknown> = {
    "": { name: "app", version: "1.0.0", dependencies: rootDeps },
  };
  for (const [name, version] of Object.entries(packages)) {
    entries[`node_modules/${name}`] = {
      version,
      resolved: `https://registry.npmjs.org/${name}/-/${tarballName(name)}-${version}.tgz`,
      integrity: "sha512-test",
    };
  }
  const lock = { name: "app", version: "1.0.0", lockfileVersion: 3, requires: true, packages: entries };
  return `${JSON.stringify(lock, null, 2)}\n`;
}

export function yarnClassicLock(packages: PackageVersions): string {
  const header =
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n";
  const blocks = Object.entries(packages).map(
    ([name, version]) =>
      `"${name}@^${version}":\n` +
      `  version "${version}"\n` +
      `  resolved "https://registry.yarnpkg.com/${name}/-/${tarballName(name)}-${version}.tgz#0"\n` +
      `  integrity sha512-test\n`,
  );
  return header + blocks.join("\n");
}

export function pnpmV9Lock(packages: PackageVersions, rootDeps: Record<string, string> = {}): string {
  const deps = Object.entries(rootDeps);
  const importer =
    deps.length === 0
      ? "  .: {}\n"
      : "  .:\n    dependencies:\n" +
        deps
          .map(
            ([name, spec]) =>
              `      '${name}':\n        specifier: '${spec}'\n        version: ${packages[name] ?? spec}\n`,
          )
          .join("");
  const keys = Object.entries(packages).map(([name, version]) => `'${name}@${version}'`);
  return (
    "lockfileVersion: '9.0'\n\n" +
    "settings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\n\n" +
    `importers:\n\n${importer}\n` +
    `packages:\n\n${keys.map((key) => `  ${key}:\n    resolution: {integrity: sha512-test}\n`).join("\n")}\n` +
    `snapshots:\n\n${keys.map((key) => `  ${key}: {}\n`).join("\n")}`
  );
}

export function bunLock(packages: PackageVersions, rootDeps: Record<string, string> = {}): string {
  const deps = Object.entries(rootDeps)
    .map(([name, spec]) => `        "${name}": "${spec}",\n`)
    .join("");
  const entries = Object.entries(packages)
    .map(([name, version]) => `    "${name}": ["${name}@${version}", "", {}, "sha512-test"],\n`)
    .join("");
  return (
    "{\n" +
    '  "lockfileVersion": 1,\n' +
    '  "workspaces": {\n' +
    '    "": {\n' +
    '      "name": "app",\n' +
    `      "dependencies": {\n${deps}      },\n` +
    "    },\n" +
    "  },\n" +
    `  "packages": {\n${entries}  },\n` +
    "}\n"
  );
}
